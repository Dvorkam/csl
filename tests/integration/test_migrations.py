"""
Unit tests for the Alembic migration setup (Task 2.3).

These tests exercise the real migration path — alembic upgrade head —
against a temporary SQLite file, then inspect the resulting schema.
They are intentionally slower than pure-unit tests (they run migrations)
but validate that the generated SQL actually matches the ORM models.
"""

import sqlite3
from pathlib import Path

import pytest
from alembic.command import downgrade, upgrade
from alembic.config import Config

EXPECTED_TABLES = {
    "users",
    "refresh_tokens",
    "machines",
    "user_machines",
    "scripts",
    "script_target_state",
    "jobs",
    "audit_log",
    "alembic_version",
}


@pytest.fixture
def alembic_cfg(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Config:
    db_file = tmp_path / "test.sqlite"
    monkeypatch.setenv("CSL_DATABASE_URL", f"sqlite+aiosqlite:///{db_file}")
    cfg = Config("alembic.ini")
    return cfg


def _table_names(db_file: Path) -> set[str]:
    conn = sqlite3.connect(db_file)
    tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    conn.close()
    return tables


def _column_names(db_file: Path, table: str) -> set[str]:
    conn = sqlite3.connect(db_file)
    cols = {row[1] for row in conn.execute(f"PRAGMA table_info({table})")}  # noqa: S608
    conn.close()
    return cols


# ---------------------------------------------------------------------------
# upgrade head
# ---------------------------------------------------------------------------


def test_upgrade_head_creates_all_tables(alembic_cfg: Config, tmp_path: Path) -> None:
    upgrade(alembic_cfg, "head")
    tables = _table_names(tmp_path / "test.sqlite")
    assert EXPECTED_TABLES.issubset(tables)


def test_upgrade_head_is_idempotent(alembic_cfg: Config, tmp_path: Path) -> None:
    upgrade(alembic_cfg, "head")
    upgrade(alembic_cfg, "head")  # must not raise
    tables = _table_names(tmp_path / "test.sqlite")
    assert EXPECTED_TABLES.issubset(tables)


