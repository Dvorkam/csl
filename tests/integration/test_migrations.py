def test_downgrade_base_removes_all_tables(alembic_cfg: Config, tmp_path: Path) -> None:
    upgrade(alembic_cfg, "head")
    downgrade(alembic_cfg, "base")
    tables = _table_names(tmp_path / "test.sqlite")
    assert tables == {"alembic_version"} or not tables  # version table may persist


# ---------------------------------------------------------------------------
# ORM round-trip against a migrated schema
#
# This is the test neither test_models.py nor the pure migration tests catch:
# it proves the migrated schema is actually compatible with the SQLAlchemy ORM
# models. test_models.py uses create_all() (bypasses Alembic), so if the
# autogenerated migration drifted from the models this test would fail while
# test_models.py would not.
# ---------------------------------------------------------------------------


def test_orm_round_trip_on_migrated_db(alembic_cfg: Config, tmp_path: Path) -> None:
    import asyncio

    from sqlalchemy import select
    from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine

    from control_station_lite.server.db.models import User

    db_url = f"sqlite+aiosqlite:///{tmp_path / 'test.sqlite'}"

    # Migration runs first (sync, uses its own asyncio.run internally).
    upgrade(alembic_cfg, "head")

    # ORM operations run in a fresh event loop — cannot nest inside pytest-asyncio.
    async def _run() -> None:
        engine = create_async_engine(db_url)
        factory = async_sessionmaker(engine, expire_on_commit=False)

        async with factory() as session:
            session.add(User(username="integration_user", password_hash="h", role="admin"))
            await session.commit()

        async with factory() as session:
            result = await session.execute(select(User).where(User.username == "integration_user"))
            user = result.scalar_one()
            assert user.role == "admin"
            assert user.disabled is False

        await engine.dispose()

    asyncio.run(_run())
